"""Regenerate web/assets/js/commands-data.js from the real CLI.

Walks the Typer command tree, so the website's command reference can't drift from
the code. Re-run after adding or changing a command:

    python web/tools/build_commands.py        # from the repo root, sagex installed
"""

import json
from pathlib import Path

import typer

from sagex import __version__
from sagex.__main__ import app

OUT = Path(__file__).resolve().parents[1] / "assets" / "js" / "commands-data.js"

# Display order + one-line blurbs for each group (the Typer help strings are terse).
GROUPS = {
    "auth": "Log in with your API key, check it, or log out.",
    "list": "Compact tables of your resources. Add --json to script against them.",
    "show": "One resource in full detail.",
    "render": "Draw a workflow as a flow tree in the terminal.",
    "run": "Run a script or workflow now and follow it live.",
    "trigger": "HTTP webhooks and cron schedules: set up, fire, follow and rotate.",
    "new": "Scaffold local files, ready to edit and push.",
    "push": "Create or update server resources from local files.",
    "copy": "Download resources to your workspace.",
    "create": "Create vaults, servers and keys.",
    "update": "Change vaults, servers and keys, or rotate a key's secret.",
    "rename": "Rename a resource in place.",
    "delete": "Delete a resource, after confirming.",
    "workspace": "Choose the local folder sagex reads from and writes to.",
    "syntax": "Copy-paste JSON snippets for workflow nodes and edges.",
}


def _clean(text: str | None) -> str:
    return " ".join((text or "").split())


def _param(p) -> dict:
    kind = type(p).__name__
    if kind.endswith("Argument"):
        name = (p.metavar or p.name).strip("[]").lower()
        return {"kind": "arg", "name": name, "required": bool(p.required), "help": _clean(getattr(p, "help", ""))}
    return {
        "kind": "opt",
        "flags": [*p.opts, *p.secondary_opts],
        "takes_value": not getattr(p, "is_flag", False),
        "help": _clean(p.help),
    }


def _command(group: str | None, name: str, cmd) -> dict:
    params = [_param(p) for p in cmd.params if p.name != "help"]
    doc = (cmd.help or "").strip().split("\n\n")
    usage = ["sagex", *([group] if group else []), name]
    for p in params:
        if p["kind"] == "arg":
            usage.append(f"<{p['name']}>" if p["required"] else f"[{p['name']}]")
    return {
        "group": group or name,
        "name": name,
        "usage": " ".join(usage),
        "summary": _clean(doc[0]),
        "details": [_clean(d) for d in doc[1:] if _clean(d)],
        "params": params,
    }


def main() -> None:
    root = typer.main.get_command(app)
    commands = []
    for gname, gcmd in root.commands.items():
        if getattr(gcmd, "commands", None):
            commands += [_command(gname, n, c) for n, c in gcmd.commands.items()]
        else:
            commands.append(_command(None, gname, gcmd))
    order = list(GROUPS)
    commands.sort(key=lambda c: order.index(c["group"]) if c["group"] in order else len(order))
    groups = [{"name": g, "blurb": b} for g, b in GROUPS.items()]

    data = {"version": __version__, "groups": groups, "commands": commands}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by web/tools/build_commands.py from the sagex CLI. Do not edit by hand.\n"
        f"window.SAGEX_COMMANDS = {json.dumps(data, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}: {len(commands)} commands in {len(groups)} groups")


if __name__ == "__main__":
    main()
